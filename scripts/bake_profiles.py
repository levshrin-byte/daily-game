#!/usr/bin/env python3
"""Bake real elevation profiles for each route into data/routes.js.

Samples evenly spaced points along the straight (Web Mercator) line between
each route's endpoints and reads elevations from the AWS Terrain Tiles
"terrarium" dataset (https://registry.opendata.aws/terrain-tiles/).
Downloaded tiles are cached in .cache/tiles/.
"""
import io, json, math, os, sys, urllib.request
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, ".cache", "tiles")
SAMPLES = 120
TILE_URL = "https://elevation-tiles-prod.s3.amazonaws.com/terrarium/{z}/{x}/{y}.png"
_tiles = {}

def tile(z, x, y):
    key = (z, x, y)
    if key not in _tiles:
        path = os.path.join(CACHE, f"{z}_{x}_{y}.png")
        if not os.path.exists(path):
            os.makedirs(CACHE, exist_ok=True)
            with urllib.request.urlopen(TILE_URL.format(z=z, x=x, y=y), timeout=60) as r:
                data = r.read()
            with open(path, "wb") as f:
                f.write(data)
        _tiles[key] = Image.open(path).convert("RGB").load()
    return _tiles[key]

def merc(lat, lon):
    x = (lon + 180) / 360
    s = math.sin(math.radians(lat))
    y = 0.5 - math.log((1 + s) / (1 - s)) / (4 * math.pi)
    return x, y

def unmerc(x, y):
    lon = x * 360 - 180
    lat = math.degrees(math.atan(math.sinh(math.pi * (1 - 2 * y))))
    return lat, lon

def pixel_elev(z, px, py):
    px %= 256 * 2 ** z
    r, g, b = tile(z, int(px // 256), int(py // 256))[int(px % 256), int(py % 256)]
    return r * 256 + g + b / 256 - 32768

def elevation(lat, lon, z):
    """Bilinear-interpolated elevation in metres."""
    mx, my = merc(lat, lon)
    n = 256 * 2 ** z
    fx, fy = mx * n - 0.5, my * n - 0.5
    x0, y0 = math.floor(fx), math.floor(fy)
    tx, ty = fx - x0, fy - y0
    e00, e10 = pixel_elev(z, x0, y0), pixel_elev(z, x0 + 1, y0)
    e01, e11 = pixel_elev(z, x0, y0 + 1), pixel_elev(z, x0 + 1, y0 + 1)
    return (e00 * (1 - tx) + e10 * tx) * (1 - ty) + (e01 * (1 - tx) + e11 * tx) * ty

def haversine(a, b):
    R = 6371.0
    la1, lo1, la2, lo2 = map(math.radians, (*a, *b))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * R * math.asin(math.sqrt(h))

def bake(route):
    a, b = route["a"], route["b"]
    pts = []
    ax, ay = merc(*a)
    bx, by = merc(*b)
    for i in range(SAMPLES):
        t = i / (SAMPLES - 1)
        pts.append(unmerc(ax + (bx - ax) * t, ay + (by - ay) * t))
    dist = sum(haversine(pts[i], pts[i + 1]) for i in range(SAMPLES - 1))
    z = 12 if dist < 40 else 11 if dist < 200 else 10
    elev = [round(elevation(lat, lon, z)) for lat, lon in pts]
    return {**route, "distanceKm": round(dist, 1), "elev": elev}

def main():
    with open(os.path.join(ROOT, "scripts", "routes.json")) as f:
        routes = json.load(f)
    out = []
    for r in routes:
        baked = bake(r)
        print(f"{r['id']:24s} {baked['distanceKm']:7.1f} km  min {min(baked['elev']):5d}  max {max(baked['elev']):5d}", file=sys.stderr)
        out.append(baked)
    js = "// Generated by scripts/bake_profiles.py. Do not edit by hand.\n"
    js += "// Elevation data: AWS Terrain Tiles (SRTM, GMTED, ETOPO1 and others).\n"
    js += "window.ROUTES = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
    with open(os.path.join(ROOT, "data", "routes.js"), "w") as f:
        f.write(js)

if __name__ == "__main__":
    main()
