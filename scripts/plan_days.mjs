// Plan three puzzles a day (Easy, Medium, Hard) from the baked routes, and write:
//  - data/days.js: window.DAYS = [[easy, medium, hard], ...] as indices into window.ROUTES (day n is DAYS[n - 1]);
//  - scripts/days.json: the same plan by route id. It is append-only, like scripts/schedule.json: days already
//    planned keep their routes, and new routes are planned onto new days at the end;
//  - data/routes.js again, with each route's `difficulty` set to the slot it plays in (1 easy, 2 medium, 3 hard).
//
// Until 13 Nov 2026 the game had one route a day: puzzle n was ROUTES[n - 1]. Those first days are pinned so
// each keeps its original route, in the slot that matches its difficulty, and results saved then still fit.
// Difficulty tiers are thirds of the difficulty score (scripts/lib/difficulty.mjs), so each tier has the
// same number of routes and every route gets played. Terrain is never changed. Run: npm run plan:days
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { difficultyScore } from "./lib/difficulty.mjs";

const ROOT = new URL("..", import.meta.url).pathname;
const LAUNCH = Date.UTC(2026, 10, 9);   // day 1, must match game.js
const todayNo = Math.floor((Date.now() - LAUNCH) / 864e5) + 1;
const ONE_A_DAY = 5;                    // days 1-5 were published as one route a day

const src = readFileSync(ROOT + "data/routes.js", "utf8");
const window = {};
new Function("window", src)(window);
const ROUTES = window.ROUTES;
const index = new Map(ROUTES.map((r, i) => [r.id, i]));
const score = ROUTES.map((r) => difficultyScore(r.elev));

// Tier by thirds of the score among the given routes (all of them, so each tier holds a third).
function tiers(list) {
  const sorted = [...list].sort((a, b) => score[a] - score[b]);
  const t = new Map();
  sorted.forEach((i, k) => t.set(i, Math.min(2, Math.floor((k * 3) / sorted.length))));
  return t;
}

const FILE = ROOT + "scripts/days.json";
let days = [];
if (existsSync(FILE)) {
  for (const [n, ids] of JSON.parse(readFileSync(FILE, "utf8")).entries()) {
    if (ids.every((id) => index.has(id))) { days.push(ids.map((id) => index.get(id))); continue; }
    if (n + 1 < todayNo + 7) throw new Error(`Day ${n + 1} lost a route (${ids.join(", ")}); it is already public or due within a week.`);
    console.error(`Unplanning day ${n + 1}: one of its routes no longer bakes.`);
    break;   // later days are re-planned
  }
}
const tier = tiers(ROUTES.map((_, i) => i));
if (!days.length) {
  // First run: pin the one-a-day routes to their days, in the slot of their tier.
  const t = tier;
  for (let n = 0; n < ONE_A_DAY; n++) { const d = [null, null, null]; d[t.get(n)] = n; days.push(d); }
}

const used = new Set(days.flat().filter((v) => v != null));
const left = ROUTES.map((_, i) => i).filter((i) => !used.has(i));
const pool = [[], [], []];
for (const i of left) pool[tier.get(i)].push(i);   // kept in ROUTES order: the old schedule's spread of regions

// Deterministic, seeded choice that keeps a day's three routes in different regions and avoids yesterday's.
let seed = 31113;
const rand = () => ((seed = (seed * 16807) % 2147483647) - 1) / 2147483646;
function pick(t, avoid, recentKinds) {
  let best = -1, bs = -Infinity;
  pool[t].forEach((i, k) => {
    const r = ROUTES[i];
    let s = -k * 0.05 + rand() * 0.5;              // roughly first come, first served
    if (avoid.includes(r.region)) s -= 3;
    if (recentKinds.includes(r.kind)) s -= 0.5;
    if (s > bs) { bs = s; best = k; }
  });
  return best < 0 ? null : pool[t].splice(best, 1)[0];
}
// Fill the empty slots of the pinned days first, then whole new days until the pools run out.
const fill = (d, prev) => {
  for (const t of [2, 0, 1]) {
    if (d[t] != null) continue;
    const others = d.filter((v) => v != null).map((v) => ROUTES[v]);
    const avoid = [...others.map((r) => r.region), ...(prev || []).map((v) => ROUTES[v].region)];
    d[t] = pick(t, avoid, others.map((r) => r.kind));
  }
  return d;
};
days.forEach((d, n) => fill(d, days[n - 1]));
while (pool.every((p) => p.length)) days.push(fill([null, null, null], days.at(-1)));
if (days.some((d) => d.includes(null))) throw new Error("Not enough routes to fill the pinned days");
const unplanned = pool.flat();

// Each route's difficulty is the slot it plays in.
const out = ROUTES.map((r) => ({ ...r }));
days.forEach((d) => d.forEach((i, t) => (out[i].difficulty = t + 1)));
const head = src.slice(0, src.indexOf("window.ROUTES = "));
writeFileSync(ROOT + "data/routes.js", head + "window.ROUTES = " + JSON.stringify(out) + ";\n");
writeFileSync(FILE, "[\n" + days.map((d) => JSON.stringify(d.map((i) => ROUTES[i].id))).join(",\n") + "\n]\n");
writeFileSync(ROOT + "data/days.js", "// Generated by scripts/plan_days.mjs. Do not edit by hand.\n" +
  "// Day n is DAYS[n - 1]: [easy, medium, hard] as indices into window.ROUTES.\n" +
  "window.DAYS = " + JSON.stringify(days) + ";\n");
console.error(`${days.length} days of three (${ROUTES.length} routes${unplanned.length ? `, ${unplanned.length} left for later` : ""}).`);
